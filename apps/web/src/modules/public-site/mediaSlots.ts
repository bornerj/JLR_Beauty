export type PublicMediaSlotCatalogItem = (typeof mediaSlotCatalog)[number];
export type MediaSlotId = PublicMediaSlotCatalogItem["id"];
export type PublicMediaSlotsSnapshot = Record<MediaSlotId, string>;

const mediaSlotIdSet = new Set<MediaSlotId>(mediaSlotCatalog.map((slot) => slot.id));

const normalizeMediaSlotUrl = (value: unknown, fallbackUrl: string): string => {
  if (typeof value !== "string") return fallbackUrl;
  const normalized = value.trim();
  return normalized || fallbackUrl;
};

export const isMediaSlotId = (value: string): value is MediaSlotId => {
  return mediaSlotIdSet.has(value as MediaSlotId);
};

export const createDefaultPublicMediaSlotsSnapshot = (): PublicMediaSlotsSnapshot => {
  const snapshot = {} as PublicMediaSlotsSnapshot;
  for (const slot of mediaSlotCatalog) {
    snapshot[slot.id] = slot.fallbackUrl;
  }
  return snapshot;
};

export const clonePublicMediaSlotsSnapshot = (
  value: PublicMediaSlotsSnapshot
): PublicMediaSlotsSnapshot => {
  const cloned = {} as PublicMediaSlotsSnapshot;
  for (const slot of mediaSlotCatalog) {
    cloned[slot.id] = value[slot.id];
  }
  return cloned;
};

export const normalizePublicMediaSlotsSnapshot = (value: unknown): PublicMediaSlotsSnapshot => {
  const candidate =
    value && typeof value === "object" && !Array.isArray(value)
      ? (value as Record<string, unknown>)
      : {};

  const normalized = {} as PublicMediaSlotsSnapshot;
  for (const slot of mediaSlotCatalog) {
    normalized[slot.id] = normalizeMediaSlotUrl(candidate[slot.id], slot.fallbackUrl);
  }
  return normalized;
};

export const getMediaSlotCatalog = (): PublicMediaSlotCatalogItem[] => {
  return mediaSlotCatalog.map((slot) => ({ ...slot }));
};

